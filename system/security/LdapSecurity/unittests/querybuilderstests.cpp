#ifdef _USE_CPPUNIT

#include "ldapquerybuilders.hpp"
#include "unittests.hpp"

// Direct call-site tests for the shared, LDAP-connection-free helpers in
// ldapquerybuilders.cpp. These are the exact functions called by the production filter/DN/ACI
// construction code in ldapconnection.cpp and aci.cpp, so calling them here (rather than
// reconstructing the expected fragment separately) pins the real call-site behavior: a future
// edit that changes what a helper emits, or that drops a call to it from production code,
// shows up as a test failure here.
class LdapQueryBuildersTest : public CppUnit::TestFixture
{
    CPPUNIT_TEST_SUITE(LdapQueryBuildersTest);
    CPPUNIT_TEST(testAppendSAMAccountNameFilter);
    CPPUNIT_TEST(testAppendResourceNameSearchFilter);
    CPPUNIT_TEST(testAppendGroupCnPrefix);
    CPPUNIT_TEST(testAppendUserUidDn);
    CPPUNIT_TEST(testAppendAciUserdnClause);
    CPPUNIT_TEST(testShouldRejectAddUserUsername);
    CPPUNIT_TEST_SUITE_END();

public:
    void testAppendSAMAccountNameFilter()
    {
        StringBuffer filter;
        appendSAMAccountNameFilter("alice", filter);
        CPPUNIT_ASSERT_EQUAL_STR("sAMAccountName=alice", filter.str());

        // Filter-metacharacters in the value must still be escaped by the shared helper.
        filter.clear();
        appendSAMAccountNameFilter("al*ice)(cn=*", filter);
        CPPUNIT_ASSERT_EQUAL_STR("sAMAccountName=al\\2aice\\29\\28cn=\\2a", filter.str());
    }

    void testAppendResourceNameSearchFilter()
    {
        // Empty/"*" searchstr leaves the base filter untouched.
        StringBuffer filter("objectClass=*");
        appendResourceNameSearchFilter(nullptr, filter);
        CPPUNIT_ASSERT_EQUAL_STR("objectClass=*", filter.str());

        filter.clear();
        filter.append("objectClass=*");
        appendResourceNameSearchFilter("*", filter);
        CPPUNIT_ASSERT_EQUAL_STR("objectClass=*", filter.str());

        // A real search string wraps the base filter and escapes filter-metacharacters.
        filter.clear();
        filter.append("objectClass=*");
        appendResourceNameSearchFilter("wu*)(uNCName=*", filter);
        CPPUNIT_ASSERT_EQUAL_STR("(&(objectClass=*)(|(uNCName=*wu\\2a\\29\\28uNCName=\\2a*)))", filter.str());
    }

    void testAppendGroupCnPrefix()
    {
        StringBuffer dn;
        appendGroupCnPrefix("admins", dn);
        CPPUNIT_ASSERT_EQUAL_STR("cn=admins,", dn.str());

        // DN-metacharacters in the group name must still be escaped.
        dn.clear();
        appendGroupCnPrefix("admins,ou=hack", dn);
        CPPUNIT_ASSERT_EQUAL_STR("cn=admins\\,ou=hack,", dn.str());
    }

    void testAppendUserUidDn()
    {
        StringBuffer userdn;
        appendUserUidDn("alice", "ou=users,dc=example,dc=com", userdn);
        CPPUNIT_ASSERT_EQUAL_STR("uid=alice,ou=users,dc=example,dc=com", userdn.str());

        userdn.clear();
        appendUserUidDn("alice,ou=hack", "ou=users,dc=example,dc=com", userdn);
        CPPUNIT_ASSERT_EQUAL_STR("uid=alice\\,ou=hack,ou=users,dc=example,dc=com", userdn.str());
    }

    // appendAciUserdnClause() must DN-escape the username (not just interpolate it raw) and
    // must produce a userdn clause whose DN fragment is byte-identical to appendUserUidDn()'s
    // output for the same inputs: CAciList::getPermissions() (aci.cpp) reconstructs a
    // candidate user's userdn via appendUserUidDn() and compares it directly against a parsed
    // ACI's stored userdn clause, so any divergence here would silently break that comparison
    // for every user. A DN-metacharacter-free username (e.g. "alice") would let both this
    // escaping check and the cross-check against appendUserUidDn() pass even if escaping were
    // silently dropped entirely, so a username containing a DN metacharacter (',') is used,
    // with the escaped form spelled out literally rather than generated by the helper under test.
    void testAppendAciUserdnClause()
    {
        StringBuffer sd;
        appendAciUserdnClause("alice,ou=hack", "ou=users,dc=example,dc=com", sd);
        CPPUNIT_ASSERT_EQUAL_STR("(userdn = \"ldap:///uid=alice\\,ou=hack,ou=users,dc=example,dc=com\");)", sd.str());

        StringBuffer userdn;
        appendUserUidDn("alice,ou=hack", "ou=users,dc=example,dc=com", userdn);
        StringBuffer expected("(userdn = \"ldap:///");
        expected.append(userdn).append("\");)");
        CPPUNIT_ASSERT_EQUAL_STR(expected.str(), sd.str());
    }

    void testShouldRejectAddUserUsername()
    {
        // Non-Active-Directory: '"' and '?' are rejected, ordinary usernames are not.
        CPPUNIT_ASSERT(shouldRejectAddUserUsername(false, "alice\"admin"));
        CPPUNIT_ASSERT(shouldRejectAddUserUsername(false, "alice?attrs=*"));
        CPPUNIT_ASSERT(!shouldRejectAddUserUsername(false, "alice"));

        // Active Directory: current behavior does not apply this check.
        CPPUNIT_ASSERT(!shouldRejectAddUserUsername(true, "alice\"admin"));
        CPPUNIT_ASSERT(!shouldRejectAddUserUsername(true, "alice?attrs=*"));
    }
};

CPPUNIT_TEST_SUITE_REGISTRATION(LdapQueryBuildersTest);
CPPUNIT_TEST_SUITE_NAMED_REGISTRATION(LdapQueryBuildersTest, "LdapQueryBuildersTest");

#endif // _USE_CPPUNIT
